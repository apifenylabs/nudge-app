// Helper functions
export function getItineraryBySlug(slug: string): Itinerary | undefined {
  return itineraries.find(i => i.slug === slug);
}

export function getAllItineraries(): Itinerary[] {
  return itineraries;
}

export function getRelatedItineraries(slug: string, count: number = 4): Itinerary[] {
  const current = getItineraryBySlug(slug);
  if (!current) return [];
  return itineraries
    .filter(i => i.id !== current.id && i.tags.some(t => current.tags.includes(t)))
    .slice(0, count);
}

export function getItinerariesByTag(tag: string): Itinerary[] {
  return itineraries.filter(i => i.tags.includes(tag));
}

export function getItineraryByStationId(stationId: string): Itinerary | undefined {
  return itineraries.find(i => i.featuredStationIds.includes(stationId));
}
